test("formatBuildReport produces a one-line-per-route summary", () => {
  const result = compile(`
    app.get("/a", (ctx) => ctx.json({}));
    app.text("/b", "x");
    app.post("/c", async (ctx) => ctx.json({}));
  `);
  const report = formatBuildReport(result);
  assert.match(report, /Discovered 3 routes/);
  assert.match(report, /✅ GET .*\/a/);
  // /b lifts to AOT now (synthesized handler), so it shows ✅ not 📄.
  assert.match(report, /✅ GET .*\/b/);
  assert.match(report, /⚠️.*POST .*\/c/);
});

test("formatBuildReport mentions the blocking rule for Bun-fallback routes", () => {
  const result = compile(`
    app.get("/x", async (ctx) => { await foo(); return ctx.json({}); });
  `);
  const report = formatBuildReport(result);
  assert.match(report, /no-await/);
});
